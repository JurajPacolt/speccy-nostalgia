"""The two fonts of the game, written as ASCII art.

`FONT_8X8` is the gothic font the game speaks with: heavy two pixel stems, bars
instead of serifs and no round corner anywhere, the same hand as the blackletter
logo in the panel. Every glyph is eight lines high; the letters use the first
seven of them and the last line keeps the rows apart. Most glyphs are seven
pixels wide so the eighth column spaces the letters - only M, W and m, w take
the whole cell, the way a scribe would let them.

`FONT_4X8` is the small font of the panel: three pixels wide and five high, two
characters in one character of the screen. There is no room for a gothic hand at
that size, so the letters are plain, and the lower case letters are the capitals
again - small capitals, which is what a manuscript would use anyway.
"""

