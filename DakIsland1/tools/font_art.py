def _small_art(rows: str) -> str:
    """One glyph of the small font: five rows of three pixels, one line down."""
    lines = ["...."]
    lines.extend(row + "." for row in rows.split(" "))
    lines.extend(["....", "....."[:4]])
    return "\n".join(lines)


