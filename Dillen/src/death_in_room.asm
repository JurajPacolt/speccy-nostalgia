;###############################################################################
;##### ASM unit for the Death, a human skeleton with the scythe in her fist. ####
;##### Room 7 is the last room before the exit, so she is standing there, on ####
;##### the way to the freedom. She is looking to the right, from where the ######
;##### player is coming, and she is waiting, who is coming to her. ##############
;###############################################################################

; Where is the Death standing. She is on the left half of the room, by the
; torch, so her scythe is lying over the path to the exit. Her feet are on the
; ground and no sprite of the room is under her, so she can be simply drawn
; again and again, without saving of the background.
DEATH_X          equ 80
DEATH_Y          equ 104
; Size of the Death in the characters.
DEATH_W          equ 7
DEATH_H          equ 7
; Frames for one image of the Death, she is moving slowly and heavily.
DEATH_DELAY      equ 8
; Length of the sequence of her movement, it must be a power of two.
DEATH_SEQ_LENGTH equ 8

;-------------------------------------------------------------------------------
; BEGIN - DeathInRoom - Main method of the Death, it's called once per frame,
;                       while her room is showed. She is chattering with her
;                       jaw and her skull is flaring up while she guards the
;                       path with the scythe.
DeathInRoom:
        ; The Death is drawn again always, when the showed room is changed. She
        ; must stand there at once, before the stars are twinkling.
        ld    a,(ActualRoomInMap)
        ld    hl,_Death_room
        cp    (hl)
        jr    z,_Death_Move
        ld    (hl),a
        xor   a
        ld    (_Death_delay),a
        ld    (_Death_step),a
        jr    _Death_Draw

_Death_Move:
        ; Slow down the movement of the Death.
        ld    hl,_Death_delay
        inc   (hl)
        ld    a,(hl)
        cp    DEATH_DELAY
        ret   nz
        ld    (hl),0

        ; The next image of the sequence.
        ld    hl,_Death_step
        ld    a,(hl)
        inc   a
        and   DEATH_SEQ_LENGTH-1
        ld    (hl),a

_Death_Draw:
        ld    a,(_Death_step)
        add   a,a ; Two bytes for the address of one image.
        ld    e,a
        ld    d,0
        ld    hl,_Death_Sequence
        add   hl,de
        ld    e,(hl)
        inc   hl
        ld    d,(hl)
        push  de
        pop   ix ; IX - actual image of the Death.

        ; The image is covering the whole place of the Death, so she is cleaning
        ; her old image by herself. The attributes are written directly to the
        ; screen, so her skull is flaring up with the color too.
        ld    b,DEATH_Y
        ld    c,DEATH_X
        ld    de,22528
        jp    PlayerDrawDynamicSprite
; END - DeathInRoom
;-------------------------------------------------------------------------------

;-------------------------------------------------------------------------------
; BEGIN - IsDeathCellReserved - Is the character cell used by the Death? The
;                               stars must keep away from her, she is drawing
;                               herself over the black night.
; B - character row.
; C - character column.
; return CF=1 - the cell belongs to the Death.
IsDeathCellReserved:
        ld    a,c
        cp    DEATH_X/8
        jr    c,_Death_CellFree
        cp    DEATH_X/8+DEATH_W
        jr    nc,_Death_CellFree
        ld    a,b
        cp    DEATH_Y/8
        jr    c,_Death_CellFree
        cp    DEATH_Y/8+DEATH_H
        jr    nc,_Death_CellFree
        scf
        ret
_Death_CellFree:
        or    a ; CF=0
        ret
; END - IsDeathCellReserved
;-------------------------------------------------------------------------------

;-------------------------------------------------------------------------------
; BEGIN - ResetDeath - The Death will be drawn again.
ResetDeath:
        ld    a,255 ; It's not a valid room in the map.
        ld    (_Death_room),a
        ret
; END - ResetDeath
;-------------------------------------------------------------------------------

; Room, in which is the Death actually drawn. 255 - none.
_Death_room:
        defb  255

; Actual image of the sequence of her movement.
_Death_step:
        defb  0

; Counter of the frames between two images of the Death.
_Death_delay:
        defb  0

; Sequence of her idle movement. She shifts her weight, breathes, tilts her
; skull and makes a small gesture, as if she is waiting for somebody to speak.
; The planted scythe only sways gently with her body.
_Death_Sequence:
        defw  SpriteDeath1
        defw  SpriteDeath2
        defw  SpriteDeath3
        defw  SpriteDeath4
        defw  SpriteDeath3
        defw  SpriteDeath2
        defw  SpriteDeath1
        defw  SpriteDeath1

